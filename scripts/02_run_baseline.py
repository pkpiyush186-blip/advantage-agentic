"""
Step 2 of the pipeline: measure the As-Is baseline, and the headroom above it.

Run:  python scripts/02_run_baseline.py

Replays three allocation strategies against the identical frozen world:

    static_split    the split set once on judgment and never changed
    monthly_manual  the As-Is manager - monthly review, last month of data,
                    moves only part of the way towards what the data implies
    oracle          per-week optimum with full knowledge (upper bound)

Writes
------
data/run_<strategy>.csv     the full 26-week run for each strategy
outputs/baseline_kpis.json  every number the report and dashboard need
outputs/baseline_report.md  a ready-to-paste summary for the final report

The oracle matters. It says how much of a gain is even available in this
world, so the 8-12% target in the proposal can be checked against the ceiling
instead of being assumed.
"""

from __future__ import annotations

import json
import sqlite3
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.baseline import (  # noqa: E402
    INITIAL_JUDGMENT_SPLIT, MANAGER_INERTIA, MonthlyManualAllocator,
    OracleAllocator, StaticSplitAllocator,
)
from src.kpis import (  # noqa: E402
    AS_IS_PROCESS, compare_outcomes, format_inr, outcome_kpis, share_series,
    weekly_series,
)
from src.policy import Rulebook  # noqa: E402
from src.world import CHANNELS, WEEKLY_BUDGET, run_allocation  # noqa: E402

DATA_DIR = ROOT / "data"
OUT_DIR = ROOT / "outputs"
DB_PATH = DATA_DIR / "advantage.db"


def _jsonable(obj):
    if hasattr(obj, "item"):
        return obj.item()
    return str(obj)


def main() -> None:
    OUT_DIR.mkdir(exist_ok=True)

    latent = pd.read_csv(DATA_DIR / "latent_weeks.csv")
    rulebook = Rulebook.load()

    strategies = {
        "static_split": StaticSplitAllocator(),
        "monthly_manual": MonthlyManualAllocator(rulebook),
        "oracle": OracleAllocator(latent, rulebook),
    }

    runs: dict[str, pd.DataFrame] = {}
    kpis: dict[str, dict] = {}

    for name, allocator in strategies.items():
        print(f"running {name} ...", flush=True)
        run = run_allocation(latent, allocator)
        run.to_csv(DATA_DIR / f"run_{name}.csv", index=False, encoding="utf-8")
        with sqlite3.connect(DB_PATH) as conn:
            run.to_sql(f"run_{name}", conn, if_exists="replace", index=False)
        runs[name] = run
        kpis[name] = outcome_kpis(run)

    manual_vs_static = compare_outcomes(
        kpis["static_split"], kpis["monthly_manual"], "static_split", "monthly_manual")
    oracle_vs_manual = compare_outcomes(
        kpis["monthly_manual"], kpis["oracle"], "monthly_manual", "oracle")

    headroom_pct = oracle_vs_manual["conversions_per_rupee"]["delta_pct"]

    payload = {
        "world": {
            "weeks": int(latent["week"].nunique()),
            "channels": list(CHANNELS),
            "weekly_budget_inr": WEEKLY_BUDGET,
            "initial_judgment_split": INITIAL_JUDGMENT_SPLIT,
            "manager_inertia": MANAGER_INERTIA,
        },
        "outcome_kpis": kpis,
        "comparisons": {
            "monthly_manual_vs_static": manual_vs_static,
            "oracle_vs_monthly_manual": oracle_vs_manual,
        },
        "primary_baseline": "monthly_manual",
        "headroom_above_baseline_pct": headroom_pct,
        "as_is_process_kpis": AS_IS_PROCESS.as_dict(),
        "manual_review_decisions": strategies["monthly_manual"].decisions,
    }

    with open(OUT_DIR / "baseline_kpis.json", "w", encoding="utf-8") as fh:
        json.dump(payload, fh, indent=2, default=_jsonable)

    weekly_series(runs["monthly_manual"]).to_csv(
        OUT_DIR / "baseline_weekly.csv", index=False, encoding="utf-8")
    share_series(runs["monthly_manual"]).to_csv(
        OUT_DIR / "baseline_shares.csv", encoding="utf-8")

    _write_report(payload, runs, OUT_DIR / "baseline_report.md")
    _print_summary(payload, strategies, headroom_pct)


def _write_report(payload: dict, runs: dict[str, pd.DataFrame], path: Path) -> None:
    k = payload["outcome_kpis"]
    proc = payload["as_is_process_kpis"]
    manual = k["monthly_manual"]

    lines = [
        "# As-Is Baseline - Measured Results",
        "",
        "Generated by `scripts/02_run_baseline.py`. All three strategies are replayed",
        "against the same frozen 26-week world (`data/latent_weeks.csv`) with the same",
        "noise stream, so the comparison is like for like.",
        "",
        "## 1. Outcome KPIs over 26 weeks",
        "",
        "| Strategy | Conversions | Conv. per lakh spent | Cost per conversion | ROAS |",
        "|---|---:|---:|---:|---:|",
    ]

    labels = {
        "static_split": "Static split (set once)",
        "monthly_manual": "**Monthly manual (As-Is baseline)**",
        "oracle": "Oracle (upper bound, not achievable)",
    }
    for name, label in labels.items():
        row = k[name]
        lines.append(
            f"| {label} | {row['total_conversions']:,} | {row['conversions_per_lakh']:.2f} | "
            f"{format_inr(row['cost_per_conversion_inr'])} | {row['roas']:.2f} |"
        )

    manual_gain = payload["comparisons"]["monthly_manual_vs_static"]["conversions_per_rupee"]["delta_pct"]
    headroom = payload["headroom_above_baseline_pct"]

    lines += [
        "",
        f"Total spend is identical in every run at {format_inr(manual['total_spend_inr'])} "
        f"({format_inr(payload['world']['weekly_budget_inr'])} per week for 26 weeks). "
        "Only the split differs, so conversions are directly comparable.",
        "",
        "## 2. What this tells us before any agent is built",
        "",
        f"- Monthly manual reallocation beats a frozen split by **{manual_gain:+.1f}%** on",
        "  conversions per rupee. The As-Is manager is not useless, and the agentic run",
        "  has to be compared against this, not against the frozen split.",
        f"- The oracle, which knows the week ahead perfectly, is **{headroom:+.1f}%** above",
        "  the manual baseline. That is the ceiling on any allocator in this world.",
    ]

    if headroom >= 12.0:
        lines.append(
            f"- The proposal target of +8-12% sits inside that ceiling, so it is a "
            f"reachable target rather than an assumed one."
        )
    else:
        lines.append(
            f"- **The proposal target of +8-12% is above or close to the {headroom:.1f}% ceiling.** "
            "The report should restate the target against measured headroom rather than "
            "defend a number this world cannot deliver."
        )

    lines += [
        "",
        "## 3. As-Is process KPIs",
        "",
        "These are **estimates** for the fictional case (proposal Section 6), not",
        "measurements. The To-Be equivalents will be counted from the agent case log.",
        "",
        "| Process KPI | As-Is | Source |",
        "|---|---:|---|",
        f"| Reallocation frequency | {proc['reallocation_frequency_per_month']:.0f} per month | estimate |",
        f"| Mean detection lag | {proc['mean_detection_lag_days']:.0f} days | estimate |",
        f"| Manager + analyst effort per cycle | {proc['manager_hours_per_cycle']:.0f} hours | estimate |",
        f"| Human touchpoints per cycle | {proc['human_touchpoints_per_cycle']:.0f} | estimate |",
        f"| Straight-through processing rate | {proc['stp_rate']:.0%} | by definition |",
        f"| Cost per cycle | {format_inr(proc['cost_per_cycle_inr'])} | "
        f"{proc['manager_hours_per_cycle']:.0f} h x {format_inr(proc['blended_hourly_rate_inr'])}/h |",
        f"| Guardrail breaches checked | not systematically | As-Is has no check |",
        "",
        "## 4. Manual review decisions",
        "",
        "The As-Is manager reviewed the split six times in 26 weeks. Each review used",
        "only the previous four weeks of reported data:",
        "",
        "| Week | From (G/M/A) | To (G/M/A) |",
        "|---|---|---|",
    ]

    for d in payload["manual_review_decisions"]:
        frm = "/".join(f"{d['from'][c]:.0%}" for c in CHANNELS)
        to = "/".join(f"{d['to'][c]:.0%}" for c in CHANNELS)
        lines.append(f"| {d['week']} | {frm} | {to} |")

    lines += [
        "",
        "## 5. Files",
        "",
        "| File | Contents |",
        "|---|---|",
        "| `data/latent_weeks.csv` | the frozen world - one row per channel-week |",
        "| `data/run_static_split.csv` | 26-week run under the frozen split |",
        "| `data/run_monthly_manual.csv` | 26-week run under the As-Is manager |",
        "| `data/run_oracle.csv` | 26-week run under perfect knowledge |",
        "| `outputs/baseline_kpis.json` | every figure above, machine readable |",
        "",
    ]

    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def _print_summary(payload: dict, strategies: dict, headroom_pct: float) -> None:
    k = payload["outcome_kpis"]

    print("\n" + "=" * 72)
    print("As-Is baseline measured")
    print("=" * 72)
    print(f"{'strategy':<18}{'conversions':>13}{'per lakh':>11}{'cost/conv':>14}{'roas':>8}")
    for name in ("static_split", "monthly_manual", "oracle"):
        row = k[name]
        print(f"{name:<18}{row['total_conversions']:>13,}{row['conversions_per_lakh']:>11.2f}"
              f"{format_inr(row['cost_per_conversion_inr']):>14}{row['roas']:>8.2f}")

    manual_gain = payload["comparisons"]["monthly_manual_vs_static"]["conversions_per_rupee"]["delta_pct"]
    print(f"\nmonthly manual vs frozen split : {manual_gain:+.1f}% conversions per rupee")
    print(f"oracle headroom above baseline : {headroom_pct:+.1f}%  <- ceiling for any allocator")

    if headroom_pct < 12.0:
        print("\nNOTE: the proposal target of +8-12% is at or above this world's ceiling.")
        print("      Restate the target against measured headroom in the report.")
    else:
        print("\nThe proposal target of +8-12% is inside the ceiling - reachable.")

    print(f"\nmanual reviews : {len(strategies['monthly_manual'].decisions)} in 26 weeks")
    print(f"report         : {OUT_DIR / 'baseline_report.md'}")
    print(f"kpis           : {OUT_DIR / 'baseline_kpis.json'}")
    print("\nDone. Next: the policy tests - python -m pytest tests -q")


if __name__ == "__main__":
    main()
