"""
Step 5 of the pipeline: run all 16 test cases and print the table.

Run:  python scripts/05_run_test_cases.py

This is the single artefact to put on screen when an examiner asks whether
the exception handling actually works. Every case builds a scenario the agent
has not seen, runs one real weekly cycle through the real graph, and checks
what the agent did against what Section 13 of the proposal said it should do.

Exits non-zero if any case fails, so it can sit in a submission checklist.

Writes
------
outputs/test_case_results.md   the table, ready to paste into the report
outputs/test_case_results.csv  the same rows, machine readable
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.testcases import run_all  # noqa: E402

OUT_DIR = ROOT / "outputs"


def main() -> int:
    OUT_DIR.mkdir(exist_ok=True)

    print("running 16 test cases through the agent graph ...\n", flush=True)
    results = run_all()

    passed = sum(1 for r in results if r["passed"])
    by_type: dict[str, list[dict]] = {}
    for row in results:
        by_type.setdefault(row["type"], []).append(row)

    width = 78
    print("=" * width)
    print(f"{'TC':<6}{'Type':<11}{'Scenario':<40}{'Result':<8}")
    print("=" * width)

    for kind in ("Normal", "Exception", "What-if"):
        for row in by_type.get(kind, []):
            mark = "PASS" if row["passed"] else "FAIL"
            print(f"{row['tc']:<6}{row['type']:<11}{row['scenario'][:38]:<40}{mark:<8}")
            print(f"      {row['evidence']}")
        print("-" * width)

    print(f"\n{passed}/{len(results)} test cases passed "
          f"({sum(1 for r in results if r['type'] == 'Normal' and r['passed'])}/8 normal, "
          f"{sum(1 for r in results if r['type'] == 'Exception' and r['passed'])}/6 exception, "
          f"{sum(1 for r in results if r['type'] == 'What-if' and r['passed'])}/2 what-if)")

    failures = [r for r in results if not r["passed"]]
    if failures:
        print("\nFAILING CASES - these are real, do not present them as passes:")
        for row in failures:
            print(f"  {row['tc']}: expected {row['expected'].lower()}")
            print(f"       got {row['evidence']}")

    _write_markdown(results, passed)
    _write_csv(results)

    print(f"\nreport : {OUT_DIR / 'test_case_results.md'}")
    return 0 if not failures else 1


def _write_markdown(results: list[dict], passed: int) -> None:
    lines = [
        "# Test Case Results",
        "",
        "Generated by `scripts/05_run_test_cases.py`. Every case constructs a scenario, "
        "runs one real weekly cycle through the LangGraph graph, and checks the agent "
        "behaviour against Section 13 of the proposal. No component is stubbed.",
        "",
        f"**{passed} of {len(results)} passed.**",
        "",
        "Each case asserts the *behaviour* the proposal specifies rather than the exact "
        "figures that happen to come out - TC03 checks that a large improvement is routed "
        "to a human, not that the shift is precisely +9.0 pp. Numbers asserted because "
        "they were observed are transcription, not testing.",
        "",
    ]

    for kind in ("Normal", "Exception", "What-if"):
        rows = [r for r in results if r["type"] == kind]
        if not rows:
            continue
        lines += [
            f"## {kind} cases",
            "",
            "| TC | Scenario | Expected behaviour | Result | What the agent did |",
            "|---|---|---|---|---|",
        ]
        for row in rows:
            mark = "PASS" if row["passed"] else "**FAIL**"
            lines.append(
                f"| {row['tc']} | {row['scenario']} | {row['expected']} | {mark} | "
                f"{row['evidence']} |"
            )
        lines.append("")

    lines += [
        "## What each case exercises",
        "",
        "| TC | Covers |",
        "|---|---|",
    ]
    for row in results:
        lines.append(f"| {row['tc']} | {row['covers']} |")

    lines += [
        "",
        "## Two cases needed new capability",
        "",
        "TC08 and TC15 described behaviour the prototype did not have. Both were built "
        "rather than having their checks softened:",
        "",
        "- **TC08 (pacing).** A channel that cannot spend what it was given now raises an "
        "`under_delivery` flag, and the guardrail caps it at roughly what it actually "
        "delivered instead of freezing it - it is not misbehaving, it simply cannot absorb "
        "the budget. Thresholds live in the rulebook (`under_delivery_pct`, "
        "`pacing_headroom_pct`).",
        "- **TC15 (budget cut).** The weekly total now lives on the case record and can be "
        "set per week, so finance changing the budget mid-season is a data change. The "
        "agent still may not change the total itself - the rulebook forbids it.",
        "",
    ]

    with open(OUT_DIR / "test_case_results.md", "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def _write_csv(results: list[dict]) -> None:
    with open(OUT_DIR / "test_case_results.csv", "w", encoding="utf-8",
              newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(results[0].keys()))
        writer.writeheader()
        writer.writerows(results)


if __name__ == "__main__":
    sys.exit(main())
